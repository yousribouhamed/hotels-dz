// Copies everything content-related from the iOS app so both apps stay identical:
// hotel data, translations (en / fr / ar), the photo index, fonts and the laurel artwork.
// Photos themselves are converted to WebP by scripts/photos-to-webp.sh.
//
// Run: node scripts/sync-from-ios.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// The iOS app sits next to this one in the repo (../ios); override with IOS_PROJECT=/path/to/ios.
const iosRoot = process.env.IOS_PROJECT ?? path.join(root, '../ios');
const ios = path.join(iosRoot, 'BoumerdesStays');
const res = path.join(ios, 'Resources');

const write = (rel, data) => {
  const out = path.join(root, rel);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, data);
  console.log('wrote', rel);
};

// 1. Hotel data
const hotels = JSON.parse(fs.readFileSync(path.join(res, 'hotels.json'), 'utf8'));
write('assets/data/hotels.json', JSON.stringify(hotels));

// 2. Translations from Localizable.strings
const parseStrings = (file) => {
  const text = fs.readFileSync(file, 'utf8');
  const table = {};
  const re = /^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";/gm;
  const unescape = (s) => s.replace(/\\n/g, '\n').replace(/\\"/g, '"').replace(/\\\\/g, '\\');
  for (const m of text.matchAll(re)) table[unescape(m[1])] = unescape(m[2]);
  return table;
};
for (const lang of ['en', 'fr', 'ar']) {
  const table = parseStrings(path.join(res, `${lang}.lproj/Localizable.strings`));
  write(`src/i18n/${lang}.json`, JSON.stringify(table, null, 1));
}

// 3. Bundled photo index: "img/a000-0.heic" -> require('../../assets/img/a000_0.webp')
const used = [...new Set(hotels.flatMap((h) => h.photos).filter((p) => !p.startsWith('http')))].sort();
const missing = used.filter((p) => !fs.existsSync(path.join(root, 'assets/img', webpName(p))));
if (missing.length) console.warn(`! ${missing.length} photos not converted yet, run scripts/photos-to-webp.sh`);
const lines = used
  .filter((p) => !missing.includes(p))
  .map((p) => `  ${JSON.stringify(p)}: require('../../assets/img/${webpName(p)}'),`);
write(
  'src/lib/bundledPhotos.ts',
  `// Generated by scripts/sync-from-ios.mjs. Do not edit.\n` +
    `// Photos shipped inside the app, keyed by the path used in hotels.json.\n` +
    `export const bundledPhotos: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
);

// 3b. Every collected review, one file per stay: ios Resources/reviews/<id>.json -> assets/reviews/,
// plus an index of lazy requires so a stay's file is only loaded when its page opens.
const revSrc = path.join(res, 'reviews');
const revDst = path.join(root, 'assets/reviews');
fs.rmSync(revDst, { recursive: true, force: true });
fs.mkdirSync(revDst, { recursive: true });
const revIds = fs.existsSync(revSrc)
  ? fs.readdirSync(revSrc).filter((f) => /^\d+\.json$/.test(f)).map((f) => parseInt(f, 10)).sort((a, b) => a - b)
  : [];
for (const id of revIds) fs.copyFileSync(path.join(revSrc, `${id}.json`), path.join(revDst, `${id}.json`));
write(
  'src/lib/reviewFiles.ts',
  `// Generated by scripts/sync-from-ios.mjs. Do not edit.\n` +
    `// All collected reviews per stay (assets/reviews/<id>.json), loaded on demand.\n` +
    `import type { Review } from './model';\n\n` +
    `export const reviewFiles: Record<number, () => Review[]> = {\n` +
    revIds.map((id) => `  ${id}: () => require('../../assets/reviews/${id}.json'),`).join('\n') +
    `\n};\n`,
);

function webpName(p) {
  return path.basename(p, path.extname(p)).replace(/-/g, '_') + '.webp';
}

// 4. Fonts and laurel artwork
fs.mkdirSync(path.join(root, 'assets/fonts'), { recursive: true });
for (const f of fs.readdirSync(path.join(res, 'Fonts'))) {
  fs.copyFileSync(path.join(res, 'Fonts', f), path.join(root, 'assets/fonts', f));
  console.log('copied font', f);
}
fs.copyFileSync(path.join(ios, 'Assets.xcassets/Laurel.imageset/laurel.png'), path.join(root, 'assets/laurel.png'));
console.log('copied laurel.png');
